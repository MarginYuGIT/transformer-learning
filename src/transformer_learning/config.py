"""
========================================
config.py - Transformer 模型配置
========================================
把所有超参数集中在一个地方，方便统一管理。
修改这里就能改变整个模型的结构。
"""


class ModelArgs:
    """
    Transformer 的所有超参数都在这里定义。

    你可以把它想象成"模型的设计图纸"——
    盖房子之前，先把层高、房间数、门窗大小全部画好。

    ┌──────────────────────────────────────────────────────────┐
    │  参数名          │  含义                                  │
    ├──────────────────┼────────────────────────────────────────┤
    │  vocab_size      │  词表大小（模型认识多少个不同的词）      │
    │  n_embd          │  词嵌入维度（每个词用多长的向量表示）    │
    │  dim             │  模型内部维度（通常等于 n_embd）         │
    │  n_heads         │  多头注意力的头数                       │
    │  n_layers        │  Encoder / Decoder 堆叠层数            │
    │  d_ff            │  前馈网络中间层维度（通常是 dim 的 4 倍）│
    │  dropout         │  Dropout 概率，防止过拟合               │
    │  max_seq_len     │  最大序列长度                           │
    └──────────────────┴────────────────────────────────────────┘
    """
    vocab_size: int = 10000       # 词表大小
    n_embd: int = 512             # 词嵌入维度
    dim: int = 512                # 模型内部维度
    n_heads: int = 8              # 注意力头数
    n_layers: int = 6             # Encoder / Decoder 层数
    d_ff: int = 2048              # 前馈网络中间层维度 (4 × dim)
    dropout: float = 0.1          # Dropout 概率
    max_seq_len: int = 512        # 最大序列长度
    pad_idx: int = 0              # 填充 token 的 ID
